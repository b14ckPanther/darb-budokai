/**
 * Pure design build: turns brand/src/tokens.json and config/design/*.yaml into generated CSS and
 * TypeScript. File I/O lives in scripts/build-design.mts; tests call these functions directly.
 */
import { mix } from './colour';
import { springCurve, toCssLinear } from './spring';

type Dict<T = unknown> = Record<string, T>;

export interface Brand {
  color: Dict<{ hex: string }>;
  type: Dict<{ family: string }>;
}

export interface TypeStyle {
  family: string;
  size?: number;
  fluid?: [number, number];
  line: number;
  tracking: number;
  weight: number;
}

export interface TokenModel {
  themes: Dict<Dict<string>>;
  contrast: { fg: string; bg: string; min: number }[];
  families: Dict<string>;
  type: Dict<TypeStyle>;
  space: Dict<number>;
  radius: Dict<number>;
  elevation: Dict<string>;
  layout: Dict<number>;
  material: Dict<number>;
  motion: {
    duration: Dict<number>;
    ease: Dict<number[]>;
    springs: Dict<{
      stiffness: number;
      damping: number;
      durationMs: number;
      points: number[];
      css: string;
    }>;
    pressScale: number;
    maxFlashesPerSecond: number;
  };
  gesture: Dict<unknown>;
  layers: Dict<number>;
  map: Dict<unknown>;
}

const HEADER =
  'Generated by npm run design from config/design and brand/src/tokens.json. Do not edit.';

function colourRef(brand: Brand, ref: unknown, where: string): string {
  if (typeof ref === 'string') {
    if (ref.startsWith('brand:')) {
      const key = ref.slice('brand:'.length);
      const c = brand.color[key];
      if (!c) throw new Error(`Unknown brand colour "${key}" at ${where}`);
      return c.hex.toUpperCase();
    }
    if (/^#[0-9a-f]{6}$/i.test(ref)) return ref.toUpperCase();
    throw new Error(`Bad colour "${ref}" at ${where}`);
  }
  if (ref && typeof ref === 'object' && 'mix' in ref) {
    const [a, b, w] = (ref as { mix: [unknown, unknown, number] }).mix;
    return mix(colourRef(brand, a, where), colourRef(brand, b, where), w);
  }
  throw new Error(`Bad colour at ${where}`);
}

function familyRef(brand: Brand, spec: { name: string; fallback: string[] }): string {
  const key = spec.name.replace(/^brand:/, '');
  const fam = brand.type[key];
  if (!fam) throw new Error(`Unknown brand type role "${key}"`);
  const quote = (f: string) => (/^[a-z-]+$/.test(f) ? f : `'${f}'`);
  return [fam.family, ...spec.fallback].map(quote).join(', ');
}

export function resolveTokens(brand: Brand, design: Dict): TokenModel {
  const themes: Dict<Dict<string>> = {};
  for (const [theme, roles] of Object.entries(design['themes'] as Dict<Dict>)) {
    themes[theme] = {};
    for (const [role, ref] of Object.entries(roles))
      themes[theme][role] = colourRef(brand, ref, `${theme}.${role}`);
  }
  const type = design['type'] as {
    families: Dict<{ name: string; fallback: string[] }>;
    scale: Dict<TypeStyle>;
  };
  const families = Object.fromEntries(
    Object.entries(type.families).map(([k, v]) => [k, familyRef(brand, v)]),
  );
  const elevation = Object.fromEntries(
    Object.entries(design['elevation'] as Dict<Dict>).map(([k, e]) => {
      const hex = colourRef(brand, e['color'], `elevation.${k}`);
      const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
      return [
        k,
        `0 ${e['y']}px ${e['blur']}px ${e['spread']}px rgb(${r} ${g} ${b} / ${e['alpha']})`,
      ];
    }),
  );
  const motion = design['motion'] as Dict;
  const samples = motion['spring-samples'] as number;
  const springs = Object.fromEntries(
    Object.entries(motion['springs'] as Dict<{ stiffness: number; damping: number }>).map(
      ([k, s]) => {
        const c = springCurve(s, samples);
        return [k, { ...s, durationMs: c.durationMs, points: c.points, css: toCssLinear(c) }];
      },
    ),
  );
  return {
    themes,
    contrast: design['contrast'] as TokenModel['contrast'],
    families,
    type: type.scale,
    space: design['space'] as Dict<number>,
    radius: design['radius'] as Dict<number>,
    elevation,
    layout: design['layout'] as Dict<number>,
    material: design['material'] as Dict<number>,
    motion: {
      duration: motion['duration'] as Dict<number>,
      ease: motion['ease'] as Dict<number[]>,
      springs,
      pressScale: motion['press-scale'] as number,
      maxFlashesPerSecond: motion['max-flashes-per-second'] as number,
    },
    gesture: design['gesture'] as Dict,
    layers: design['layers'] as Dict<number>,
    map: design['map'] as Dict,
  };
}

function round(n: number): number {
  return Math.round(n * 10000) / 10000;
}

function fluid(min: number, max: number, layout: Dict<number>): string {
  const lo = layout['fluid-min'];
  const hi = layout['fluid-max'];
  const slope = (max - min) / (hi - lo);
  const intercept = min - slope * lo;
  return `clamp(${min}rem, ${round(intercept)}rem + ${round(slope * 100)}vw, ${max}rem)`;
}

export function buildTokensCss(m: TokenModel): string {
  const out: string[] = [`/* ${HEADER} */`, ':root {'];
  const add = (k: string, v: string | number) => out.push(`  --${k}: ${v};`);
  for (const [role, hex] of Object.entries(m.themes['dark'])) add(`color-${role}`, hex);
  for (const [k, v] of Object.entries(m.families)) add(`font-${k}`, v);
  for (const [k, t] of Object.entries(m.type)) {
    add(`type-${k}-family`, `var(--font-${t.family})`);
    add(`type-${k}-size`, t.fluid ? fluid(t.fluid[0], t.fluid[1], m.layout) : `${t.size}rem`);
    add(`type-${k}-line`, t.line);
    add(`type-${k}-tracking`, `${t.tracking}em`);
    add(`type-${k}-weight`, t.weight);
  }
  for (const [k, v] of Object.entries(m.space)) add(`space-${k}`, v === 0 ? '0' : `${v}rem`);
  for (const [k, v] of Object.entries(m.radius))
    add(`radius-${k}`, k === 'pill' ? `${v}px` : `${v}rem`);
  for (const [k, v] of Object.entries(m.elevation)) add(`elevation-${k}`, v);
  for (const [k, v] of Object.entries(m.layout)) {
    if (k === 'desktop-from') add(k, `${v}px`);
    else if (k === 'measure') add(k, `${v}rem`);
    else add(k, `${v}rem`);
  }
  add('bar-alpha', m.material['bar-alpha']);
  add('bar-blur', `${m.material['bar-blur']}px`);
  add('sheet-alpha', m.material['sheet-alpha']);
  add('scrim-alpha', m.material['scrim-alpha']);
  for (const [k, v] of Object.entries(m.motion.duration)) add(`dur-${k}`, `${v}ms`);
  for (const [k, v] of Object.entries(m.motion.ease))
    add(`ease-${k}`, `cubic-bezier(${v.join(', ')})`);
  for (const [k, s] of Object.entries(m.motion.springs)) {
    add(`spring-${k}`, s.css);
    add(`spring-${k}-dur`, `${s.durationMs}ms`);
  }
  add('press-scale', m.motion.pressScale);
  for (const [k, v] of Object.entries(m.layers)) add(`layer-${k}`, v);
  out.push('}', '');
  return out.join('\n');
}

export function buildTokensTs(m: TokenModel): string {
  return [
    `/* ${HEADER} */`,
    `export const TOKENS = ${JSON.stringify(m, null, 2)} as const;`,
    '',
    'export type Tokens = typeof TOKENS;',
    '',
  ].join('\n');
}

interface IconConfig {
  ui: Dict<string>;
  sigil: string[];
}

export function buildIconsTs(
  cfg: IconConfig,
  solar: { icons: Dict<{ body: string }> },
  sigils: Dict<string>,
): string {
  const entries: [string, { kind: 'ui' | 'sigil'; source: string; body: string }][] = [];
  for (const [name, ref] of Object.entries(cfg.ui)) {
    const id = ref.replace(/^solar:/, '');
    const icon = solar.icons[id];
    if (!ref.startsWith('solar:') || !icon)
      throw new Error(`Icon "${name}" points to missing ${ref}`);
    entries.push([name, { kind: 'ui', source: ref, body: icon.body }]);
  }
  for (const name of cfg.sigil) {
    const svg = sigils[name];
    if (!svg) throw new Error(`Missing sigil ${name}`);
    const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
    entries.push([
      name,
      { kind: 'sigil', source: `config/design/sigils/${name}.svg`, body: body.trim() },
    ]);
  }
  const obj = Object.fromEntries(entries);
  return [
    `/* ${HEADER} Solar icons by 480 Design, CC BY 4.0. Sigils are original. */`,
    `export const ICONS = ${JSON.stringify(obj, null, 2)} as const;`,
    '',
    'export type IconName = keyof typeof ICONS;',
    '',
  ].join('\n');
}

function dataModule(source: string, name: string, data: unknown): string {
  return [
    `/* Generated by npm run design from ${source}. Do not edit. */`,
    `export const ${name} = ${JSON.stringify(data, null, 2)} as const;`,
    '',
  ].join('\n');
}

export function buildCopyTs(files: Dict<Dict>): string {
  return dataModule('config/copy/en', 'COPY', files);
}

export function buildSeedTs(files: Dict<Dict>): string {
  return dataModule('config/seed/demo (demo data only)', 'DEMO_SEED', files);
}
